import type { ActivityKind, Coordinates, Mood } from '@/types/itinerary';

/**
 * The venue pool the planner composes from.
 *
 * Three tiers, because real trips have three tiers:
 *
 *   `venues`   — the named, specific things. Consumed without replacement so a
 *                plan never suggests the same restaurant twice.
 *   `dayTrips` — whole-day excursions, used once the city pool thins out on
 *                longer trips. This is also just how people actually travel.
 *   `districts`— real neighbourhoods, used to build unstructured "open"
 *                blocks. The fallback is still concrete: a named area with
 *                coordinates and a reason to be there, never "free time".
 *
 * Together these guarantee the planner can fill any trip length the UI allows
 * without ever repeating itself or emitting filler.
 */

/** When a venue actually makes sense in the day. */
export type Slot = 'morning' | 'midday' | 'afternoon' | 'evening' | 'any';

export interface VenueSeed {
  kind: ActivityKind;
  title: string;
  summary: string;
  address: string;
  coordinates: Coordinates;
  /** Per person, in the city's currency. */
  price: number;
  durationMinutes: number;
  tags: string[];
  imageSeed: string;
  moods: Mood[];
  slot: Slot;
  note?: string;
}

export interface DayTripSeed {
  title: string;
  theme: string;
  blocks: VenueSeed[];
}

export interface DistrictSeed {
  name: string;
  reason: string;
  coordinates: Coordinates;
  moods: Mood[];
  imageSeed: string;
}

export interface CityVenues {
  venues: VenueSeed[];
  dayTrips: DayTripSeed[];
  districts: DistrictSeed[];
}

